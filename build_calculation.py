"""Build calculation practice from stable, reviewable question JSON."""
from pathlib import Path
import hashlib,json,re
ROOT=Path(__file__).resolve().parent;BASE=ROOT/'question-bank/calculation'
CATEGORIES=[('calendar','历法与起遁'),('relations','五行与干支'),('noble','禄马与贵人'),('gods','日值与神煞'),('marriage','婚嫁参数'),('doushou','斗首与番化')]
def build():
 questions=json.loads((BASE/'questions.json').read_text())
 terms={t['id']:t for t in json.loads((ROOT/'question-bank/glossary/terms.json').read_text())}
 assert len({q['id'] for q in questions})==len(questions)
 assert len({q['q'] for q in questions})==len(questions)
 for q in questions:
  t=terms[q['term']]
  assert q['id'].startswith('zc-') and q['rev']>=1 and q['category'] in dict(CATEGORIES)
  assert t.get('derivation') and q['basis']==t['derivation']['basis']
  assert q['topic']==t['title'] and len(q['steps'])>=2 and q['e']==' '.join(q['steps'])
  assert len(q['w'])==3 and len(set([q['a'],*q['w']]))==4
  assert q['inputs']['method'] and not re.search('中观|视频|奇门|六爻|TODO|待补',json.dumps(q,ensure_ascii=False))
 d=dict(questions=questions,categories=[dict(id=k,title=v) for k,v in CATEGORIES])
 d['version']=hashlib.sha256(json.dumps(d,ensure_ascii=False,sort_keys=True).encode()).hexdigest()[:12]
 (BASE/'data.js').write_text('/* Generated by build_calculation.py. */\nwindow.ZERI_CALC='+json.dumps(d,ensure_ascii=False,separators=(',',':'))+';\n')
 print(f'推算练习：{len(questions)}题 / {len(set(q["term"] for q in questions))}种起法 / {len(CATEGORIES)}类；{d["version"]}')
 return d
if __name__=='__main__':build()
