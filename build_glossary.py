"""Build the independent, sourced glossary and terminology practice data."""
from pathlib import Path
import hashlib,json,re
ROOT=Path(__file__).resolve().parent;BASE=ROOT/'question-bank/glossary'
CATEGORIES=[('reading','读通书与用事'),('calendar','历法与时间'),('annual','卷首年景与节俗'),('home','搬家与家居'),('build','修造与土工'),('marriage','婚嫁礼俗'),('funeral','丧葬礼俗'),('ritual','祭祀与仪式'),('business','工商与财货'),('daily','日常与农牧'),('space','山向与空间'),('relations','五行与干支关系'),('shensha','日值与神煞'),('methods','择日方法与斗首')]
def norm(x):return re.sub(r'\s+','',x)
def build():
 T=json.loads((BASE/'terms.json').read_text());Q=json.loads((BASE/'questions.json').read_text());S=json.loads((BASE/'sources.json').read_text());by={t['id']:t for t in T};cats=dict(CATEGORIES)
 assert len(by)==len(T) and len({t['title'] for t in T})==len(T)
 P=json.loads((ROOT/'_src/pages.json').read_text()) if (ROOT/'_src/pages.json').exists() else None
 for t in T:
  assert t['category'] in cats and all(t.get(x) for x in ['definition','example','distinguish']),t['id']
  assert t['sources'] or t['refs'],('没有来源',t['id'])
  for s in t['sources']:assert s in S['sources'],s
  for r in t['refs']:
   assert 1<=r['page']<=1832 and r['quote'].strip(),t['id']
   if P is not None:assert norm(r['quote']) in norm(P[r['page']-1]),('原文定位失效',t['id'])
  for x in t['related']:assert x in by,x
  if t.get('derivation'):
   d=t['derivation'];assert d.get('basis') and len(d.get('steps',[]))>=2 and d.get('example'),t['id']
  if t['category']=='shensha':assert t.get('judgement'),('神煞缺吉凶说明',t['id'])
  if t.get('judgement'):
   j=t['judgement'];assert j['nature'] in ['吉','凶','随用事','参数','吉凶总称','宜静忌动'] and j['basis'] and j['scope'],t['id']
   assert j.get('level','') in ['','大吉','小吉','大凶','小凶','中煞','次凶'],t['id']
   for sid in j['sources']:assert sid in S['sources'] and sid in t['sources'],t['id']
   for r in j['refs']:
    assert r in t['refs'],t['id']
   if j.get('level'):assert j['sources'] or j['refs'],('分级缺依据',t['id'])
  if t.get('pinyin'):assert re.fullmatch(r"[a-zāáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜüêńňḿ\s'-]+",t['pinyin']),t['id']
 assert len({q['id'] for q in Q})==len(Q) and len({q['q'] for q in Q})==len(Q)
 for q in Q:
  t=by[q['term']];assert q['rev']>=1 and q['category']==t['category']
  assert len(q['w'])==3 and len(set([q['a'],*q['w']]))==4,q['id']
  assert len(q['e'])>=20,q['id']
  assert not re.search('中观|视频|奇门|六爻',json.dumps(q,ensure_ascii=False)),q['id']
 data=dict(terms=T,questions=Q,categories=[dict(id=i,title=n) for i,n in CATEGORIES],sources=S['sources'],checked=S['checked'])
 assert not re.search('中观|视频|奇门|六爻',json.dumps(data,ensure_ascii=False))
 # Reuse existing page images only; unavailable page images never become broken URLs.
 assets=json.loads((ROOT/'question-bank/page-assets.json').read_text())
 data['pages']={str(r['page']):assets[str(r['page'])]['file'] for t in T for r in t['refs'] if str(r['page']) in assets}
 data['version']=hashlib.sha256(json.dumps(data,sort_keys=True,ensure_ascii=False).encode()).hexdigest()[:12]
 (BASE/'data.js').write_text('/* Generated by build_glossary.py. */\nwindow.ZERI_TERMS='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n')
 print(f"名词构建：{len(T)}词 / {len(Q)}题 / {len(CATEGORIES)}类 / {len(S['sources'])}个网络出处；{data['version']}；原文定位{'已核' if P is not None else '缺本地原页，未核'}")
 return data
if __name__=='__main__':build()
