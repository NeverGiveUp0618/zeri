"""Build the question-only site from original-course metadata and stable question IDs."""
from pathlib import Path
import hashlib,json,re

ROOT=Path(__file__).resolve().parent
def norm(s):return re.sub(r'\s+','',s)
def build():
    catalog=json.loads((ROOT/'question-bank/sources.json').read_text())
    questions=json.loads((ROOT/'question-bank/questions.json').read_text())
    pages=json.loads((ROOT/'_src/pages.json').read_text()) if (ROOT/'_src/pages.json').exists() else None
    ids=set();stems=set();chapters={c['id']:(b,c) for b in catalog['books'] for c in b['chapters']}
    for q in questions:
        assert q['id'] not in ids,q['id'];ids.add(q['id'])
        assert norm(q['q']) not in stems,q['q'];stems.add(norm(q['q']))
        assert len(q['w'])==3 and len(set([q['a'],*q['w']]))==4,q['id']
        b,c=chapters[q['chapter']];assert q['book']==b['id'] and c['start']<=q['page']<=c['end'],q['id']
        assert len(q['a'])<=max(map(len,q['w'])),('正解独自最长，须逐题复查',q['id'])
        assert not re.search('中观|视频|奇门|六爻',json.dumps(q,ensure_ascii=False)),q['id']
        if pages is not None:assert norm(q['quote']) in norm(pages[q['page']-1]),('原文不匹配',q['id'])
    data={'catalog':catalog,'questions':questions}
    data['version']=hashlib.sha256(json.dumps(data,ensure_ascii=False,sort_keys=True).encode()).hexdigest()[:12]
    (ROOT/'question-bank/data.js').write_text('/* Generated by build_question_bank.py. */\nwindow.ZERI_BANK='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n')
    print(f"题库构建：{len(questions)}题，{len({q['chapter'] for q in questions})}个原章节，{len({q['page'] for q in questions})}页依据；{data['version']}")
if __name__=='__main__':build()
